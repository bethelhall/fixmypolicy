def test_single_statement(statement, original_policy_structure, args, policy_name=None, policy_index=None):
    """Test a single statement by creating a temporary policy and running validation"""
    
    # Create temporary policy with just this statement
    temp_policy_file = create_temporary_policy(statement, original_policy_structure)
    
    # Initialize temp_args outside try block
    temp_args = None
    
    try:
        # Create temporary args for this statement
        temp_args = ap.Namespace(**vars(args))
        temp_args.policy1 = temp_policy_file
        temp_args.policy2 = None
        
        # Generate a unique output name for this statement
        stmt_id = statement.get('Sid', statement.get('sid', 'UnknownStmt'))
        temp_args.output = f"{args.output}_temp_{stmt_id}"
        
        # Run the SMT translation and validation
        call_translator(temp_args)
        statement_results = validate_requests_for_statement(temp_args, policy_name, policy_index)
        
        # Determine if this statement has any failures
        total_requests = len(statement_results)
        failed_requests = sum(1 for r in statement_results if not r['is_correct'])
        
        is_faulty = failed_requests > 0
        accuracy = ((total_requests - failed_requests) / total_requests * 100) if total_requests > 0 else 100
        
        # Print detailed error breakdown with policy tracking
        policy_info = f"Policy {policy_index}" if policy_index is not None else f"Policy {policy_name}" if policy_name else "Policy"
        
        if is_faulty:
            must_deny_got_allow = sum(1 for r in statement_results if r['expected_effect'] == 'deny' and r['actual_result'] == 'allow')
            must_allow_got_deny = sum(1 for r in statement_results if r['expected_effect'] == 'allow' and r['actual_result'] == 'deny')
            solver_errors = sum(1 for r in statement_results if r['actual_result'] == 'error')
            
            print(f"{policy_info} - Statement {stmt_id}: {total_requests} requests, {failed_requests} failures, {accuracy:.1f}% accuracy")
            print(f"  Must-deny-got-allow: {must_deny_got_allow}")
            print(f"  Must-allow-got-deny: {must_allow_got_deny}")
            if solver_errors > 0:
                print(f"  Solver errors: {solver_errors}")
        else:
            print(f"{policy_info} - Statement {stmt_id}: {total_requests} requests, {failed_requests} failures, {accuracy:.1f}% accuracy")
        
        return is_faulty, statement_results, accuracy
        
    except Exception as e:
        policy_info = f"Policy {policy_index}" if policy_index is not None else f"Policy {policy_name}" if policy_name else "Policy"
        print(f"{policy_info} - Error testing statement {statement.get('Sid', statement.get('sid', 'Unknown'))}: {e}")
        return True, [], 0  # Consider it faulty if there's an error
        
    finally:
        # Clean up temporary files
        if os.path.exists(temp_policy_file):
            os.unlink(temp_policy_file)
        
        # Clean up SMT files if temp_args was created
        if temp_args is not None:
            smt_file = f"{temp_args.output}_1.smt2"
            if os.path.exists(smt_file):
                os.unlink(smt_file)

def identify_faulty_statements(args):
    """Main function to identify faulty statements and create erroneous policy"""
    reset_solver_calls()

    
    # Determine which policy file to use
    policy_file = None
    if args.policy1:
        policy_file = args.policy1
    elif args.policy2:
        policy_file = args.policy2
    else:
        print("Error: No policy file specified")
        return
    
    # Load requests
    if not args.requests:
        print("Error: No requests given to validate")
        return
    
    # Extract policy name/index from file path for tracking
    policy_name = os.path.basename(policy_file)
    policy_index = None
    
    # Try to extract numeric index from filename (e.g., "5.json" -> 5)
    try:
        base_name = os.path.splitext(policy_name)[0]
        if base_name.isdigit():
            policy_index = int(base_name)
    except:
        pass
    
    # Extract policy structure and statements
    original_policy_structure, statements = extract_policy_statements(policy_file)
    
    policy_info = f"Policy {policy_index}" if policy_index is not None else f"Policy {policy_name}"
    print(f"{policy_info}: Found {len(statements)} statements in policy")
    
    faulty_statements_with_analysis = []
    all_results = []
    statement_analysis = []
    
    print(f"\n{'='*60}")
    print(f"TESTING INDIVIDUAL STATEMENTS - {policy_info}")
    print(f"{'='*60}")
    
    for stmt_idx, statement in enumerate(statements):
        stmt_id = statement.get('Sid', statement.get('sid', f'Statement_{stmt_idx + 1}'))
        print(f"\n{policy_info} - Testing Statement {stmt_idx + 1}/{len(statements)}: {stmt_id}")
        print(f"  Effect: {statement.get('Effect', 'N/A')}")
        print(f"  Action: {statement.get('Action', 'N/A')}")
        print(f"  Resource: {statement.get('Resource', 'N/A')}")
        
        is_faulty, statement_results, accuracy = test_single_statement(statement, original_policy_structure, args, policy_name, policy_index)
        
        # Add statement metadata to results with policy tracking
        for result in statement_results:
            result['policy_name'] = policy_name
            result['policy_index'] = policy_index
            result['policy_file'] = policy_file
            result['statement_index'] = stmt_idx + 1
            result['statement_id'] = stmt_id
            result['statement_effect'] = statement.get('Effect', 'Unknown')
            result['statement_action'] = str(statement.get('Action', 'Unknown'))
            result['statement_resource'] = str(statement.get('Resource', 'Unknown'))
        
        all_results.extend(statement_results)
        
        stmt_analysis = {
            'policy_name': policy_name,
            'policy_index': policy_index,
            'policy_file': policy_file,
            'statement_index': stmt_idx + 1,
            'statement_id': stmt_id,
            'statement': statement,
            'is_faulty': is_faulty,
            'accuracy': accuracy,
            'total_requests': len(statement_results),
            'failed_requests': sum(1 for r in statement_results if not r['is_correct']),
            'results': statement_results 
        }
        
        statement_analysis.append(stmt_analysis)
        
        if is_faulty:
            faulty_statements_with_analysis.append(stmt_analysis)
            print(f"  FAULTY - Added to erroneous policy")
        else:
            print(f"  PASSED - All requests validated correctly")
    
    print(f"\n{policy_info}: Running complete policy validation for fault localization...")
    complete_policy_results = validate_requests(args)
    
    fault_results = perform_fault_localization(complete_policy_results, original_policy_structure, statements, args)
    
    save_fault_localization_results(fault_results, args, policy_name, policy_index)
    
    overall_accuracy = generate_reports(statement_analysis, all_results, args, policy_name, policy_index)
    total_calls = get_solver_calls()
    print(f"\n{policy_info}: Total solver calls: {total_calls}")
    
    return faulty_statements_with_analysis, statement_analysis, overall_accuracy

def validate_requests_for_statement(args, policy_name=None, policy_index=None):
    """Validate requests against a single statement policy"""

    smt_file = f"{args.output}_1.smt2"
    base_smt = []
    with open(smt_file) as f:
        for line in f:
            if line.strip() not in ("(check-sat)", "(get-model)"):
                base_smt.append(line)
    base_smt = ''.join(base_smt)

    # Load requests
    with open(args.requests) as f:
        data = json.load(f)

