def extract_policy_statements(policy_file):
    """Extract individual statements from a policy file"""
    with open(policy_file, 'r') as f:
        policy_data = json.load(f)
    
    statements = []
    if 'Statement' in policy_data:
        statements = policy_data['Statement']
    elif isinstance(policy_data, list):
        statements = policy_data
    
    return policy_data, statements

def create_temporary_policy(statement, original_policy_structure):
    """Create a temporary policy file with just one statement"""
    temp_policy = original_policy_structure.copy()
    temp_policy['Statement'] = [statement]
    
    # Create temporary file
