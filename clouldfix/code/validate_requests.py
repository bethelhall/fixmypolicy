def test_request_against_policy(request_data, policy_file, args):
    """Test a single request against a policy and return the result"""
    
    # Create temporary args for this test
    temp_args = ap.Namespace(**vars(args))
    temp_args.policy1 = policy_file
    temp_args.policy2 = None
    temp_args.output = f"{args.output}_fault_test_{int(time.time())}"
    
    try:
        # Run the SMT translation
        call_translator(temp_args)
        
        # Load the SMT file generated by call_translator
        smt_file = f"{temp_args.output}_1.smt2"
        base_smt = []
        with open(smt_file) as f:
            for line in f:
                if line.strip() not in ("(check-sat)", "(get-model)"):
                    base_smt.append(line)
        base_smt = ''.join(base_smt)

        # Extract request components
        action = request_data['action']
        resource = request_data['resource']
        principal = request_data['principal']
        condition = request_data['condition']

        solver = Solver()
        smt_parts = [base_smt]

        # Assert action & resource
        a = action.lower()
        r = resource
        smt_parts.append(f'(assert (= action "{a}"))\n')
        smt_parts.append(f'(assert (= resource "{r}"))\n')

        if principal and principal != 'None':
            smt_parts.append(f'(assert (= principal "{principal}"))\n')

        # Assert conditions
        if condition and condition != 'None':
            condition_dict = eval(condition) if isinstance(condition, str) and condition != 'None' else condition
            if condition_dict:
                for key, val in condition_dict.items():
                    k = key.replace(':', '.')
                    vals = val if isinstance(val, list) else [val]
                    clauses = []
                    for v in vals:
                        if isinstance(v, int):
                            clauses.append(f"(= {k} {v})")
                        elif isinstance(v, str) and "Ip" not in key:
                            ev = v
                            clauses.append(f'(= {k} "{ev}")')
                        elif isinstance(v, str):
                            addr, pref = bit_string(v)
                            re_expr = re2smt(addr[:pref])
                            clauses.append(f"(str.in.re {k} {re_expr})")
                    if clauses:
                        if len(clauses) > 1:
                            smt_parts.append(f"(assert (or {' '.join(clauses)}))\n")
                        else:
                            smt_parts.append(f"(assert {clauses[0]})\n")

        smt_parts.append("(check-sat)")
        full_smt = ''.join(smt_parts).replace('\x00', '\x01')

        # Solve
        solver.from_string(full_smt)
        increment_solver_calls()
        solver_result = solver.check()
        
        # Determine actual result
        actual_result = 'allow' if solver_result == sat else 'deny'
        
        return actual_result
        
    except Exception as e:
        print(f"Error testing request against policy: {e}")
        return 'error'
        
    finally:
        # Clean up temporary files
        smt_file = f"{temp_args.output}_1.smt2"
        if os.path.exists(smt_file):
            os.unlink(smt_file)
def perform_fault_localization(all_results, original_policy_structure, statements, args):
    """
    Perform fault localization according to the specified algorithm:
    
    Case 1: request(rm) is allowed but should be denied
    Case 2a: rm is denied but should be allowed (explicitly denied)
    Case 2b: rm is denied but should be allowed (implicitly denied)
    """
    print("\n" + "="*80)
    print("PERFORMING FAULT LOCALIZATION")
    print("="*80)
    
    fault_localization_results = []
    
    # Get all misclassified requests
    misclassified_requests = [r for r in all_results if not r['is_correct']]
    
    print(f"Found {len(misclassified_requests)} misclassified requests to analyze")
    
    # Separate allow and deny statements from policy P
    s_allow = [s for s in statements if s.get('Effect', '').lower() == 'allow']
    s_deny = [s for s in statements if s.get('Effect', '').lower() == 'deny']
    
    print(f"Policy P has {len(s_allow)} Allow statements and {len(s_deny)} Deny statements")
    
    for req in misclassified_requests:
        print(f"\nAnalyzing misclassified request: {req['individual_request_id']}")
        print(f"  Expected: {req['expected_effect']}, Got: {req['actual_result']}")
        
        request_data = {
            'action': req['action'],
            'resource': req['resource'],
            'principal': req['principal'],
            'condition': req['condition']
        }
        
        responsible_statements = []
        fault_type = ""
        
        if req['expected_effect'] == 'deny' and req['actual_result'] == 'allow':
            # CASE 1: Request should be denied but is allowed
            print(f"  CASE 1: Request should be denied but is explicitly allowed")
            fault_type = "should_be_denied_but_explicitly_allowed"
            
            s_allow_of_rm = []
            
            # For si in S_allow, create Pi with si only
            for stmt in s_allow:
                stmt_id = stmt.get('Sid', stmt.get('sid', 'UnknownStmt'))
                print(f"    Testing Allow statement: {stmt_id}")
                
                # Create Pi = {si} (policy containing only this allow statement)
                pi_file = create_temporary_policy(stmt, original_policy_structure)
                
                try:
                    result = test_request_against_policy(request_data, pi_file, args)
                    print(f"      Result with Pi containing only {stmt_id}: {result}")
                    
                    # If rm is allowed by Pi, add si to s_allow_of_rm
                    if result == 'allow':
                        s_allow_of_rm.append(stmt_id)
                        responsible_statements.append({
                            'statement_id': stmt_id,
                            'statement': stmt,
                            'effect': 'Allow'
                        })
                        print(f" Statement {stmt_id} allows this request")
                    
                finally:
                    if os.path.exists(pi_file):
                        os.unlink(pi_file)
            
            print(f"  s_allow_of_rm = {s_allow_of_rm}")
            
        elif req['expected_effect'] == 'allow' and req['actual_result'] == 'deny':
            # CASE 2: Request should be allowed but is denied
            print(f"  CASE 2: Request should be allowed but is denied")
            
            # Create universal policy P' that allows everything
            p_prime_stmt = {
                "Sid": "AllowEverything",
                "Effect": "Allow", 
                "Action": "*",
                "Resource": "*"
            }
            
            s_deny_of_rm = []
            
            # For si in s_deny: create Pii = P' ∪ si
            for stmt in s_deny:
                stmt_id = stmt.get('Sid', stmt.get('sid', 'UnknownStmt'))
                print(f"    Testing Deny statement: {stmt_id}")
                
                # Create Pii = P' ∪ si (universal allow + this deny statement)
                pii_statements = [p_prime_stmt, stmt]
                pii_file = create_policy_with_statements(pii_statements, original_policy_structure)
                
                try:
                    result = test_request_against_policy(request_data, pii_file, args)
                    print(f"      Result with Pii (universal_allow + {stmt_id}): {result}")
                    
                    # If rm is denied by Pii, add si to s_deny_of_rm
                    if result == 'deny':
                        s_deny_of_rm.append(stmt_id)
                        responsible_statements.append({
                            'statement_id': stmt_id,
                            'statement': stmt,
                            'effect': 'Deny'
                        })
                        print(f" Statement {stmt_id} denies this request")
                    
                finally:
                    if os.path.exists(pii_file):
                        os.unlink(pii_file)
            
            # Determine sub-case based on s_deny_of_rm
            if s_deny_of_rm:
                # CASE 2a: Explicitly denied by statement(s)
                fault_type = "should_be_allowed_but_explicitly_denied"
                print(f"  CASE 2a: Explicitly denied by statements: {s_deny_of_rm}")
            else:
                # CASE 2b: Implicitly denied (no explicit deny statements affect it)
                fault_type = "should_be_allowed_but_implicitly_denied"
                print(f"  CASE 2b: Implicitly denied (no explicit deny statement affects request)")
                # responsible_statements remains empty for implicit denial
        
        # Store the fault localization result
        fault_result = {
            'request_id': req['individual_request_id'],
            'request_object_id': req['request_object_id'],
            'action': req['action'],
            'resource': req['resource'],
            'principal': req['principal'],
            'condition': req['condition'],
            'expected_effect': req['expected_effect'],
            'actual_result': req['actual_result'],
            'fault_type': fault_type,
            'responsible_statements': responsible_statements,
            'responsible_statement_ids': [s['statement_id'] for s in responsible_statements]
        }
        
        fault_localization_results.append(fault_result)
        
        print(f"  Final analysis:")
        print(f"    Fault type: {fault_type}")
        print(f"    Responsible statements: {[s['statement_id'] for s in responsible_statements]}")
    
    return fault_localization_results


